import { expect, test, type Page } from '@playwright/test'
import { openEditor } from './helpers'

const field = (page: Page, label: string, index = 0) =>
  page.locator(`xpath=//div[normalize-space(.)="${label}"]/following-sibling::div[1]//input`).nth(index)

const pick = (page: Page, name: string) => page.locator('select').first().selectOption({ label: name })

test('adds shapes from the shape picker and edits their parameters', async ({ page }) => {
  await openEditor(page)
  await page.getByTitle('All shapes').click()
  const picker = page.getByRole('dialog', { name: 'Shapes' })
  await expect(picker.getByRole('button')).toHaveCount(15)
  await picker.getByRole('button', { name: 'Star' }).click()
  await expect(picker).toHaveCount(0)
  await expect(page.locator('input[value="Star"]')).toBeVisible()
  await page.getByLabel('Points').fill('7')
  await page.getByLabel('Points').blur()
  await expect(page.getByLabel('Points')).toHaveValue('7')

  await page.getByTitle('All shapes').click()
  await page.getByRole('dialog', { name: 'Shapes' }).getByRole('button', { name: 'Text' }).click()
  await page.getByLabel('Text', { exact: true }).fill('Hello')
  await expect(page.getByLabel('Text', { exact: true })).toHaveValue('Hello')
  await page.getByTitle('Undo').click()
  await expect(page.getByLabel('Text', { exact: true })).toHaveValue('Text')
})

test('cuts holes out of a group and keeps the parts editable', async ({ page }) => {
  await openEditor(page)
  await page.keyboard.press('1')
  await page.keyboard.press('3')
  await page.getByRole('radio', { name: 'Hole' }).click()
  await expect(page.getByRole('radio', { name: 'Hole' })).toHaveAttribute('aria-checked', 'true')
  await page.keyboard.press('ControlOrMeta+a')
  await page.keyboard.press('ControlOrMeta+g')
  await expect(page.getByText(/group “Group”/)).toBeVisible()
  await expect(page.getByRole('radio', { name: 'Hole' })).toHaveAttribute('aria-checked', 'false')

  await page.getByTitle('Export for 3D printing').click()
  const dialog = page.getByRole('dialog', { name: 'Export for 3D printing' })
  const download = page.waitForEvent('download')
  await dialog.getByRole('button', { name: 'Download STL' }).click()
  expect((await download).suggestedFilename()).toBe('scene.stl')
  await page.keyboard.press('Escape')

  await pick(page, 'Cylinder')
  await expect(page.getByRole('radio', { name: 'Hole' })).toHaveAttribute('aria-checked', 'true')
  await page.keyboard.press('ControlOrMeta+a')
  await page.keyboard.press('ControlOrMeta+Shift+g')
  await expect(page.getByText(/group “Group”/)).toHaveCount(0)
  await pick(page, 'Cylinder')
  await page.getByRole('radio', { name: 'Solid' }).click()
  await expect(page.getByRole('radio', { name: 'Solid' })).toHaveAttribute('aria-checked', 'true')
})

test('aligns and mirrors the selection', async ({ page }) => {
  await openEditor(page)
  await page.keyboard.press('1')
  await page.keyboard.press('2')
  await pick(page, 'Sphere')
  await field(page, 'Position (m)').fill('3')
  await field(page, 'Position (m)', 1).fill('2')
  await field(page, 'Position (m)', 1).blur()
  await page.keyboard.press('ControlOrMeta+a')
  await page.getByTitle('Align X min').click()
  await pick(page, 'Sphere')
  await expect(field(page, 'Position (m)')).toHaveValue('0')
  await page.keyboard.press('d')
  await expect(field(page, 'Position (m)', 1)).toHaveValue('0.5')

  await pick(page, 'Box')
  await page.getByTitle('Mirror across X').click()
  await expect(field(page, 'Scale')).toHaveValue('-1')
  await page.getByTitle('Undo').click()
  await expect(field(page, 'Scale')).toHaveValue('1')
})

test('measures between two points until cleared', async ({ page }) => {
  await openEditor(page)
  await page.keyboard.press('1')
  await page.keyboard.press('Escape')
  await page.getByTitle('Ruler').click()
  await expect(page.getByTitle('Ruler')).toHaveAttribute('aria-pressed', 'true')
  await page.mouse.click(640, 520)
  await page.mouse.click(800, 600)
  const label = page.locator('[data-ruler]')
  await expect(label).toContainText(/\d+(\.\d+)? m/)
  await page.keyboard.press('Escape')
  await expect(page.getByTitle('Ruler')).toHaveAttribute('aria-pressed', 'false')
  await expect(label).toBeVisible()
  await page.getByTitle('Clear measurement').click()
  await expect(label).toHaveCount(0)
})
